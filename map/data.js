/* ============================================================
   各省生育数据层（当前为示例数据，待替换为真实数据集）

   ▍如何替换为真实数据：
   把下面 window.BIRTH_DATA.series 里每个省份的 births / rate 数组
   替换为真实值即可（与 years 等长、按年份顺序对齐）：
     births —— 历年出生人口，单位：万人
     rate   —— 历年出生率，单位：‰
   键名必须与地图 GeoJSON 的省份全名一致（含"省/市/自治区/特别行政区"
   后缀，见 map/china-geo.js 中各 feature 的 properties.name）。
   例如（Excel 两列年份、一列广东省出生人口、一列广东省出生率，
   导出后填入数组即可；也可以另写转换脚本生成本文件）：
     "广东省": { births: [1112, 1085, ...], rate: [14.7, 14.2, ...] }
   若某省某年缺数据，对应位置填 null，页面会显示"暂无数据"。
   ============================================================ */

(function () {
  "use strict";

  var YEARS = [];
  for (var y = 1995; y <= 2025; y++) YEARS.push(y);

  /* 全国历年出生人口（万人），国家统计局公报/年鉴口径 —— 仅用于生成示例数据 */
  var NAT = [2052, 2057, 2028, 1934, 1827, 1771, 1702, 1647, 1599, 1593,
             1617, 1585, 1594, 1608, 1615, 1592, 1604, 1635, 1640, 1687,
             1655, 1883, 1765, 1523, 1465, 1202, 1062, 956, 902, 954, 792];

  /* 省份配置：[GeoJSON 全名, 常用简称, 常住人口(万人, 约2020), 出生份额(示意)] */
  var CFG = [
    ["北京市", "北京", 2189, 0.016],
    ["天津市", "天津", 1387, 0.010],
    ["河北省", "河北", 7461, 0.052],
    ["山西省", "山西", 3492, 0.028],
    ["内蒙古自治区", "内蒙古", 2400, 0.020],
    ["辽宁省", "辽宁", 4259, 0.023],
    ["吉林省", "吉林", 2407, 0.017],
    ["黑龙江省", "黑龙江", 3185, 0.018],
    ["上海市", "上海", 2487, 0.014],
    ["江苏省", "江苏", 8475, 0.050],
    ["浙江省", "浙江", 6457, 0.034],
    ["安徽省", "安徽", 6103, 0.046],
    ["福建省", "福建", 4154, 0.034],
    ["江西省", "江西", 4519, 0.036],
    ["山东省", "山东", 10153, 0.068],
    ["河南省", "河南", 9937, 0.075],
    ["湖北省", "湖北", 5775, 0.035],
    ["湖南省", "湖南", 6644, 0.048],
    ["广东省", "广东", 12601, 0.090],
    ["广西壮族自治区", "广西", 5013, 0.044],
    ["海南省", "海南", 1008, 0.012],
    ["重庆市", "重庆", 3209, 0.028],
    ["四川省", "四川", 8367, 0.052],
    ["贵州省", "贵州", 3856, 0.038],
    ["云南省", "云南", 4721, 0.040],
    ["西藏自治区", "西藏", 365, 0.006],
    ["陕西省", "陕西", 3953, 0.028],
    ["甘肃省", "甘肃", 2502, 0.023],
    ["青海省", "青海", 592, 0.008],
    ["宁夏回族自治区", "宁夏", 720, 0.010],
    ["新疆维吾尔自治区", "新疆", 2585, 0.028],
    ["台湾省", "台湾", 2357, 0.017],
    ["香港特别行政区", "香港", 748, 0.004],
    ["澳门特别行政区", "澳门", 68, 0.0008]
  ];

  /* 确定性伪随机（相同输入永远得到相同扰动，保证每次打开数据一致） */
  function wiggle(pi, yi) {
    var s = Math.sin(yi * 12.9898 + (pi + 1) * 78.233) * 43758.5453;
    return (s - Math.floor(s)) - 0.5; /* [-0.5, 0.5] */
  }

  var sumF = 0;
  CFG.forEach(function (c) { sumF += c[3]; });

  var series = {};
  CFG.forEach(function (c, pi) {
    var births = [], rate = [];
    for (var i = 0; i < YEARS.length; i++) {
      /* 出生人口 = 全国值 × 份额（±4% 确定性扰动） */
      var b = NAT[i] * (c[3] / sumF) * (1 + wiggle(pi, i) * 0.08);
      b = Math.round(b * 10) / 10;
      births.push(b);
      /* 出生率 = 出生人口 / 常住人口 × 1000 */
      rate.push(Math.round(b / c[2] * 1000 * 100) / 100);
    }
    series[c[0]] = { births: births, rate: rate };
  });

  /* 亦提供简称映射，供面板显示 */
  var SHORT = {};
  CFG.forEach(function (c) { SHORT[c[0]] = c[1]; });

  window.BIRTH_DATA = {
    years: YEARS,
    series: series,   /* ← 用真实数据集替换这里（格式见文件头注释） */
    short: SHORT,
    isSample: true    /* 替换为真实数据后改为 false，页面上的"示例数据"提示会消失 */
  };
})();
